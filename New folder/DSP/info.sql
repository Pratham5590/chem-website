-- DSP Chemistry database schema for Neon PostgreSQL.
-- Run this in the Neon SQL Editor before importing existing records.

CREATE TABLE IF NOT EXISTS resources (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(255) NOT NULL,
    "class" VARCHAR(50) NOT NULL,
    chapter VARCHAR(255) NOT NULL,
    description TEXT,
    type VARCHAR(100),
    file_path VARCHAR(500),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS videos (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(255) NOT NULL,
    "class" VARCHAR(50) NOT NULL,
    chapter VARCHAR(255) NOT NULL,
    description TEXT,
    file_path VARCHAR(500),
    thumbnail_path VARCHAR(500),
    duration VARCHAR(50),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS queries (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL,
    subject VARCHAR(255),
    message TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS resources_created_at_idx
    ON resources (created_at DESC);

CREATE INDEX IF NOT EXISTS videos_created_at_idx
    ON videos (created_at DESC);

CREATE INDEX IF NOT EXISTS queries_created_at_idx
    ON queries (created_at DESC);
